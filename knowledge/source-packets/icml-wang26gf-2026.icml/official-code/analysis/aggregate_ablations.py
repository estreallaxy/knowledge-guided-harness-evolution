#!/usr/bin/env python3
"""Aggregate 2^3 factorial ablation results across multiple models.

Reads every JSON in data/results/ablation_real/ and produces:
  (1) a per-model table of main effects (NB, ET, PR) and interactions
  (2) a LaTeX table ready for the experiments section
  (3) a summary line for the headline NB-dominance claim

Usage:
    python analysis/aggregate_ablations.py
    python analysis/aggregate_ablations.py --results-dir data/results/ablation_real
    python analysis/aggregate_ablations.py --latex-out paper_neurips2026/figures/ablation_table.tex
"""

import argparse
import json
import sys
from pathlib import Path
from collections import defaultdict


def load_runs(results_dir: Path) -> list:
    """Load all ablation JSON files; keep the most recent run per (model, provider)."""
    by_key = {}
    for f in sorted(results_dir.glob("ablation_*.json")):
        try:
            data = json.loads(f.read_text())
        except (json.JSONDecodeError, OSError) as e:
            print(f"skip {f.name}: {e}", file=sys.stderr)
            continue
        key = (data.get("model", ""), data.get("provider", ""))
        # Keep only the run with the most seeds per (model, provider)
        prev = by_key.get(key)
        if prev is None or data.get("num_seeds", 0) >= prev.get("num_seeds", 0):
            data["_source_file"] = f.name
            by_key[key] = data
    return list(by_key.values())


def extract_metrics(run: dict) -> dict:
    """Pull main effects and interactions into a flat row."""
    a = run.get("analysis", {})
    me = a.get("main_effects", {})
    ix = a.get("interactions", {})
    cfgs = run.get("configs", {})

    def me_val(k):
        v = me.get(k)
        if isinstance(v, dict):
            return v.get("effect", v.get("difference", float("nan")))
        return v if v is not None else float("nan")

    return {
        "model": run.get("model", "?"),
        "provider": run.get("provider", "?"),
        "n_seeds": run.get("num_seeds", 0),
        "rho_baseline": cfgs.get("nb0_et0_pr0", {}).get("contamination_rate", float("nan")),
        "rho_full": cfgs.get("nb1_et1_pr1", {}).get("contamination_rate", float("nan")),
        "main_NB": me_val("name_binding"),
        "main_ET": me_val("event_triggering"),
        "main_PR": me_val("propagation"),
        "ix_NB_ET": ix.get("nb_x_et", float("nan")),
        "ix_NB_PR": ix.get("nb_x_pr", float("nan")),
        "ix_ET_PR": ix.get("et_x_pr", float("nan")),
        "ix_NB_ET_PR": ix.get("nb_x_et_x_pr", float("nan")),
        "_source_file": run.get("_source_file", ""),
    }


def fmt(x, pct=False):
    if x != x:  # NaN
        return "--"
    return f"{100*x:+.1f}" if pct else f"{x:+.3f}"


def print_console(rows: list):
    print(f"\nLoaded {len(rows)} (model, provider) pairs:\n")
    hdr = f"{'Model':<25} {'n':>3} {'rho_000':>8} {'rho_111':>8} "\
          f"{'NB':>7} {'ET':>7} {'PR':>7} {'NB:ET':>7} {'NB:PR':>7} {'ET:PR':>7}"
    print(hdr)
    print("-" * len(hdr))
    rows_sorted = sorted(rows, key=lambda r: -abs(r["main_NB"]) if r["main_NB"] == r["main_NB"] else 0)
    for r in rows_sorted:
        print(f"{r['model'][:24]:<25} {r['n_seeds']:>3} "
              f"{fmt(r['rho_baseline'], pct=True):>8} {fmt(r['rho_full'], pct=True):>8} "
              f"{fmt(r['main_NB']):>7} {fmt(r['main_ET']):>7} {fmt(r['main_PR']):>7} "
              f"{fmt(r['ix_NB_ET']):>7} {fmt(r['ix_NB_PR']):>7} {fmt(r['ix_ET_PR']):>7}")
    print()
    nb_dominates = sum(1 for r in rows
                       if r["main_NB"] == r["main_NB"]
                       and abs(r["main_NB"]) > max(abs(r["main_ET"]), abs(r["main_PR"])))
    print(f"NB main effect dominates ET and PR in {nb_dominates}/{len(rows)} models.")


LATEX_TEMPLATE = r"""% Auto-generated by analysis/aggregate_ablations.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\small
\caption{{Extended $2^3$ factorial ablation across {n_models} models. Main effects
and 2-way interactions on contamination rate. $\rho_{{000}}$: baseline (no PSE);
$\rho_{{111}}$: full PSE. Effects in absolute change of $\rho \in [0,1]$.
Main effect of name binding (NB) dominates event triggering (ET) and propagation
(PR) in {n_dominates}/{n_models} models, confirming Corollary~\ref{{cor:nb-dominance}}.}}
\label{{tab:ablation-extended}}
\begin{{tabular}}{{lrrrrrrrrr}}
\toprule
Model & $n$ & $\rho_{{000}}$ & $\rho_{{111}}$ & NB & ET & PR & NB$\times$ET & NB$\times$PR & ET$\times$PR \\
\midrule
{rows}
\bottomrule
\end{{tabular}}
\end{{table}}
"""


def write_latex(rows: list, out_path: Path):
    body_lines = []
    rows_sorted = sorted(rows, key=lambda r: -(r["main_NB"] if r["main_NB"] == r["main_NB"] else -9))
    for r in rows_sorted:
        cells = [
            r["model"].replace("_", r"\_"),
            str(r["n_seeds"]),
            fmt(r["rho_baseline"], pct=True),
            fmt(r["rho_full"], pct=True),
            fmt(r["main_NB"]),
            fmt(r["main_ET"]),
            fmt(r["main_PR"]),
            fmt(r["ix_NB_ET"]),
            fmt(r["ix_NB_PR"]),
            fmt(r["ix_ET_PR"]),
        ]
        body_lines.append(" & ".join(cells) + r" \\")
    n_dominates = sum(1 for r in rows
                      if r["main_NB"] == r["main_NB"]
                      and abs(r["main_NB"]) > max(abs(r["main_ET"]), abs(r["main_PR"])))
    out_path.write_text(LATEX_TEMPLATE.format(
        n_models=len(rows),
        n_dominates=n_dominates,
        rows="\n".join(body_lines),
    ))
    print(f"Wrote LaTeX table: {out_path} ({len(rows)} rows)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="data/results/ablation_real",
                    type=Path, help="Directory containing ablation_*.json")
    ap.add_argument("--latex-out", default=None, type=Path,
                    help="If set, write a LaTeX table to this path")
    args = ap.parse_args()

    if not args.results_dir.exists():
        sys.exit(f"results dir not found: {args.results_dir}")

    runs = load_runs(args.results_dir)
    if not runs:
        sys.exit(f"no ablation_*.json files in {args.results_dir}")
    rows = [extract_metrics(r) for r in runs]
    print_console(rows)
    if args.latex_out:
        args.latex_out.parent.mkdir(parents=True, exist_ok=True)
        write_latex(rows, args.latex_out)


if __name__ == "__main__":
    main()
