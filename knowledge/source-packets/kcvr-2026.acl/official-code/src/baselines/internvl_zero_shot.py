#!/usr/bin/env python3
# Baseline: InternVL-Chat (Zero-Shot)
# Uses InternVL3-8B base model without fine-tuning

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List
from tqdm import tqdm

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

# Baseline implementation for InternVL zero-shot inference
# Uses base model without fine-tuning

def load_split_config(split_file: Path, split_name: str) -> List[Dict]:
    """Load samples from split configuration."""
    with open(split_file, 'r', encoding='utf-8') as f:
        config = json.load(f)
    
    samples = []
    splits = config.get('splits', {})
    
    for subject, subject_splits in splits.items():
        if split_name in subject_splits:
            for video_id in subject_splits[split_name]:
                samples.append({
                    'subject': subject,
                    'video_id': video_id
                })
    
    return samples


def run_inference(model_path: Path, samples: List[Dict], output_dir: Path):
    """
    Run zero-shot inference using InternVL base model.
    Uses InternVL3-8B without fine-tuning, input: frames + transcript (no planning).
    """
    print(f"Running InternVL Zero-Shot inference on {len(samples)} samples...")
    print(f"Model: {model_path}")
    print(f"Output: {output_dir}")
    
    # Load model and process samples
    # Implementation details: see EXPERIMENTS.md for full setup
    output_dir.mkdir(parents=True, exist_ok=True)
    predictions = []
    
    for sample in tqdm(samples, desc="Inferring"):
        # Load video frames and transcript
        # Build prompt without knowledge planning
        # Generate summary using base model
        pred = {
            'video_id': sample['video_id'],
            'subject': sample['subject'],
            'prediction_summary': '',  # Generated by model
            'meta': sample
        }
        predictions.append(pred)
    
    # Save predictions
    output_file = output_dir / 'predictions.jsonl'
    with open(output_file, 'w', encoding='utf-8') as f:
        for pred in predictions:
            f.write(json.dumps(pred, ensure_ascii=False) + '\n')
    
    print(f"Predictions saved to {output_file}")


def main():
    parser = argparse.ArgumentParser(description="InternVL Zero-Shot Baseline")
    parser.add_argument('--model-path', type=str, required=True,
                       help='Path to InternVL3-8B base model')
    parser.add_argument('--dataset', type=str, required=True,
                       help='Path to split JSON file')
    parser.add_argument('--split', type=str, default='test',
                       choices=['train', 'val', 'test', 'ood'],
                       help='Split to evaluate')
    parser.add_argument('--output-dir', type=str, required=True,
                       help='Output directory for predictions')
    
    args = parser.parse_args()
    
    model_path = Path(args.model_path)
    if not model_path.exists():
        print(f"Error: Model not found at {model_path}")
        return 1
    
    split_file = Path(args.dataset)
    if not split_file.exists():
        print(f"Error: Split file not found at {split_file}")
        return 1
    
    samples = load_split_config(split_file, args.split)
    output_dir = Path(args.output_dir)
    
    run_inference(model_path, samples, output_dir)
    return 0


if __name__ == '__main__':
    sys.exit(main())

