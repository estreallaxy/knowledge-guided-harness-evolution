import numpy as np
import pandas as pd
from scipy.stats import chi2_contingency, spearmanr, ttest_ind

def calculate_advanced_metrics(data_dict, name="Dataset"):
    # 1. 数据预处理
    score_map = {
        "NEG_2": 1, "NEG_3": 2, "NEG_4": 3, "NEG_1": 4, "NEG_5": 5, "STOP": 6,
        "NEU": 7, "POS": 8
    }
    
    raw_data_cat = []
    raw_data_score = []

    for cat, dist in data_dict.items():
        for rating_key, count in dist.items():
            if rating_key not in score_map: continue 
            score_val = score_map[rating_key]
            raw_data_cat.extend([cat] * count)
            raw_data_score.extend([score_val] * count)
            
    df = pd.DataFrame({"Category": raw_data_cat, "Score": raw_data_score})
    
    print(f"--- {name} 高级指标分析 ---")
    
    # --- 指标 1: Cramér's V (基于卡方检验) ---
    contingency_table = pd.crosstab(df['Category'], df['Score'])
    # 捕获 p 值 (p_chi2)
    chi2, p_chi2, _, _ = chi2_contingency(contingency_table)
    n = contingency_table.sum().sum()
    min_dim = min(contingency_table.shape) - 1
    cramers_v = np.sqrt(chi2 / (n * min_dim))
    print(f"1. Cramér's V (关联强度): {cramers_v:.4f} (p-value: {p_chi2:.4e})")
    
    # --- 指标 2: Spearman's Rank Correlation ---
    cat_means = df.groupby("Category")["Score"].mean().sort_values()
    cat_rank_map = cat_means.to_dict()
    df['Category_Mean_Score'] = df['Category'].map(cat_rank_map)
    
    # 捕获 p 值 (p_spearman)
    spearman_corr, p_spearman = spearmanr(df['Category_Mean_Score'], df['Score'])
    print(f"2. Spearman Correlation: {spearman_corr:.4f} (p-value: {p_spearman:.4e})")
    
    # --- 指标 3: Cohen's d & t-test (均值差异检验) ---
    if "NE" in df['Category'].unique():
        ne_scores = df[df['Category'] == 'NE']['Score']
        error_scores = df[df['Category'] != 'NE']['Score']
        
        # 计算 Cohen's d
        mean_diff = ne_scores.mean() - error_scores.mean()
        n1, n2 = len(ne_scores), len(error_scores)
        s1, s2 = ne_scores.var(), error_scores.var()
        s_pooled = np.sqrt(((n1 - 1) * s1 + (n2 - 1) * s2) / (n1 + n2 - 2))
        cohens_d = mean_diff / s_pooled
        
        # 计算 t 检验的 p 值 (验证差异是否显著)
        t_stat, p_ttest = ttest_ind(ne_scores, error_scores, equal_var=False)
        
        print(f"3. Cohen's d (效应量): {cohens_d:.4f}")
        print(f"   t-test Significance (均值差异显著性): p = {p_ttest:.4e}")
        print(f"   (NE均值: {ne_scores.mean():.2f}, Error均值: {error_scores.mean():.2f})")
    else:
        print("3. Cohen's d: 未找到 'NE' 类别，跳过")
        
    print("-" * 30 + "\n")

# 运行 (假设 data_wildchat 和 data_lmsys 已定义)
calculate_advanced_metrics(data_wildchat, "WildChat")
